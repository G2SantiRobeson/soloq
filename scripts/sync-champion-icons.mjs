import { copyFile, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const source = path.join(root, "champ_icons");
const destination = path.join(root, "public", "champ-icons");
const files = (await readdir(source))
  .filter((name) => /^[1-9]\d*\.png$/.test(name))
  .sort((a, b) => parseInt(a) - parseInt(b));
await mkdir(destination, { recursive: true });
for (const name of files) {
  const data = await readFile(path.join(source, name));
  if (data.subarray(0, 8).toString("hex") !== "89504e470d0a1a0a")
    throw new Error(`Invalid PNG: ${name}`);
  await copyFile(path.join(source, name), path.join(destination, name));
}
// Generated URLs refer only to validated source files. Stale copied files are never referenced.
const manifest = `// Generated by npm run icons:sync. Edit champ_icons, not this file.\nexport const LOCAL_CHAMPION_IDS: readonly number[] = ${JSON.stringify(files.map((name) => parseInt(name)))};\n`;
await writeFile(path.join(root, "src/lib/champion-icons.generated.ts"), manifest);
console.log(
  `Published ${files.length} local champion icons from champ_icons to public/champ-icons.`,
);
