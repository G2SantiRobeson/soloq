import { readdir, readFile, copyFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
const source = path.join(root, "rank_icon");
const destination = path.join(root, "public/rank-icons");
await mkdir(destination, { recursive: true });
const assets = {};
const wings = {};
for (const name of (await readdir(source)).sort()) {
  const match =
    /^Rank=(Iron|Bronze|Silver|Gold|Platinum|Emerald|Diamond|Master|Grandmaster|Challenger)\.png$/.exec(
      name,
    );
  if (!match) continue;
  const { data, info } = await sharp(path.join(source, name))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let left = info.width,
    top = info.height,
    right = -1,
    bottom = -1;
  for (let y = 0; y < info.height; y++)
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * info.channels + info.channels - 1] > 0) {
        left = Math.min(left, x);
        right = Math.max(right, x);
        top = Math.min(top, y);
        bottom = Math.max(bottom, y);
      }
    }
  if (right < 0) throw new Error(`Empty rank emblem: ${name}`);
  // Only adjust the viewport. Preserve the original PNG byte-for-byte, including every alpha pixel.
  const side = Math.ceil(Math.max(right - left + 1, bottom - top + 1) * 1.08);
  const viewBox = `${(left + right + 1 - side) / 2} ${(top + bottom + 1 - side) / 2} ${side} ${side}`;
  const filename = `${match[1].toLowerCase()}.png`;
  await copyFile(path.join(source, name), path.join(destination, filename));
  assets[match[1].toUpperCase()] = {
    src: `/rank-icons/${filename}`,
    width: info.width,
    height: info.height,
    viewBox,
  };
}
await mkdir(path.join(destination, "wings"), { recursive: true });
for (const name of (await readdir(path.join(source, "Wings"))).sort()) {
  if (
    !/^(Iron|Bronze|Silver|Gold|Platinum|Emerald|Diamond|Master|Grand|Challenger)\.png$/.test(name)
  )
    continue;
  const original = path.join(source, "Wings", name);
  const { data, info } = await sharp(original)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let left = info.width,
    top = info.height,
    right = -1,
    bottom = -1;
  for (let y = 0; y < info.height; y++)
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * info.channels + info.channels - 1] > 0) {
        left = Math.min(left, x);
        right = Math.max(right, x);
        top = Math.min(top, y);
        bottom = Math.max(bottom, y);
      }
    }
  if (right < 0) throw new Error(`Empty rank wings: ${name}`);
  const side = Math.ceil(Math.max(right - left + 1, bottom - top + 1) * 1.04);
  const x = (left + right + 1 - side) / 2;
  const y = (top + bottom + 1 - side) / 2;
  const tier = name.replace(".png", "").replace(/^Grand$/, "Grandmaster");
  const filename = `${tier.toLowerCase()}.png`;
  // These ten supplied frames share the same circular opening in the original canvas.
  // Place the avatar over the opening, preserving the frame and its central jewel.
  wings[tier.toUpperCase()] = {
    src: `/rank-icons/wings/${filename}`,
    width: info.width,
    height: info.height,
    viewBox: `${x} ${y} ${side} ${side}`,
    avatarLeft: ((386 - x) / side) * 100,
    avatarTop: ((706 - y) / side) * 100,
    avatarSize: (384 / side) * 100,
  };
  // Photoshop text metadata adds ~20 MB to each frame. Drop text chunks only:
  // retain IDAT bytes, alpha, palette and color profile without re-encoding any pixels.
  const png = await readFile(original);
  const chunks = [png.subarray(0, 8)];
  for (let offset = 8; offset < png.length; ) {
    const length = png.readUInt32BE(offset);
    const end = offset + length + 12;
    const type = png.toString("ascii", offset + 4, offset + 8);
    if (!["iTXt", "tEXt", "zTXt"].includes(type)) chunks.push(png.subarray(offset, end));
    offset = end;
  }
  await writeFile(path.join(destination, "wings", filename), Buffer.concat(chunks));
}
await writeFile(
  path.join(root, "src/lib/rank-assets.generated.ts"),
  `// Generated by npm run ranks:sync. Original artwork lives in rank_icon.\nexport const RANK_ASSETS: Record<string, {src: string; width: number; height: number; viewBox: string}> = ${JSON.stringify(assets, null, 2)};\nexport const RANK_WINGS: Record<string, {src: string; width: number; height: number; viewBox: string; avatarLeft: number; avatarTop: number; avatarSize: number}> = ${JSON.stringify(wings, null, 2)};\n`,
);
console.log(
  `Published ${Object.keys(assets).length} complete rank emblems; original pixels preserved.`,
);
